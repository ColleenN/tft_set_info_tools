"""Row generators for the BigQuery reference tables, one schema per table.

The seed generators in seeds.py add columns depending on the data: item rows
get a column per item type and component, and unit rows a column per stat the
raw data happens to carry. That's fine for a CSV regenerated by hand, but a
table loaded from every snapshot needs the same columns every time. So here
item types and components become long-form rows, and unit stats a JSON column.

JSON columns hold the parsed value (dict/list), not a serialized string.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable

from tft_set_info_tools.set_data import TFTSetData
from tft_set_info_tools.set_data.legacy_vocab import COMPONENT_COLUMN_NAMES, ITEM_TYPE_COLUMN_NAMES

_ITEM_TYPES_BY_COLUMN = {column: item_type for item_type, column in ITEM_TYPE_COLUMN_NAMES.items()}
_COMPONENTS_BY_COLUMN = {column: component for component, column in COMPONENT_COLUMN_NAMES.items()}


@dataclass(frozen=True)
class ReferenceTable:
    columns: dict[str, str]
    """Column name -> BigQuery type, in table order."""
    generate: Callable[[TFTSetData], list[dict]]


def _trait_tiers(set_data: TFTSetData) -> list[dict]:
    return [
        {
            "name": tier.trait_name,
            "api_name": tier.trait_api_name,
            "type": tier.style.name,
            "tier_min_units": tier.min_units,
            "tier_max_units": tier.max_units,
            "tier_style": tier.style.value,
            "tier_variables": tier.variables,
            "desc": tier.trait_desc,
        }
        for tier in set_data.get_trait_tiers()
    ]


def _items(set_data: TFTSetData) -> list[dict]:
    return [
        {
            "item_name": item.name,
            "item_api_name": item.api_name,
            "effects": item.effects,
            "trait_granted": item.trait_granted,
            "unique": item.unique,
            "num_craftables": item.num_craftables,
        }
        for item in set_data.get_equippable_items()
    ]


def _item_types(set_data: TFTSetData) -> list[dict]:
    return [
        {"item_api_name": item.api_name, "item_type": _ITEM_TYPES_BY_COLUMN[column].type_name}
        for item in set_data.get_equippable_items()
        for column, count in item.type_counts.items()
        if count
    ]


def _item_components(set_data: TFTSetData) -> list[dict]:
    return [
        {
            "item_api_name": item.api_name,
            "component": _COMPONENTS_BY_COLUMN[column].value,
            "count": count,
        }
        for item in set_data.get_equippable_items()
        for column, count in item.component_counts.items()
        if count
    ]


def _augments(set_data: TFTSetData) -> list[dict]:
    return [
        {
            "item_name": augment.name,
            "item_api_name": augment.api_name,
            "tier": augment.tier.name if augment.tier is not None else None,
            "effects": augment.effects,
        }
        for augment in set_data.get_normalized_augments()
    ]


def _units(set_data: TFTSetData) -> list[dict]:
    return [
        {
            "name": unit.name,
            "api_name": unit.api_name,
            "cost": unit.cost,
            "role": unit.role,
            "shop_unit": unit.shop_unit,
            "stats": unit.stats,
        }
        for unit in set_data.get_normalized_units()
    ]


def _unit_innate_traits(set_data: TFTSetData) -> list[dict]:
    return [
        {
            "name": unit_trait.unit_name,
            "api_name": unit_trait.unit_api_name,
            "trait_name": unit_trait.trait_name,
            "trait_api_name": unit_trait.trait_api_name,
        }
        for unit_trait in set_data.get_normalized_unit_traits()
    ]


REFERENCE_TABLES: dict[str, ReferenceTable] = {
    "trait_tiers": ReferenceTable(
        {
            "name": "STRING",
            "api_name": "STRING",
            "type": "STRING",
            "tier_min_units": "INT64",
            "tier_max_units": "INT64",
            "tier_style": "INT64",
            "tier_variables": "JSON",
            "desc": "STRING",
        },
        _trait_tiers,
    ),
    "items": ReferenceTable(
        {
            "item_name": "STRING",
            "item_api_name": "STRING",
            "effects": "JSON",
            "trait_granted": "STRING",
            "unique": "BOOL",
            "num_craftables": "INT64",
        },
        _items,
    ),
    "item_types": ReferenceTable(
        {"item_api_name": "STRING", "item_type": "STRING"},
        _item_types,
    ),
    "item_components": ReferenceTable(
        {"item_api_name": "STRING", "component": "STRING", "count": "INT64"},
        _item_components,
    ),
    "augments": ReferenceTable(
        {"item_name": "STRING", "item_api_name": "STRING", "tier": "STRING", "effects": "JSON"},
        _augments,
    ),
    "units": ReferenceTable(
        {
            "name": "STRING",
            "api_name": "STRING",
            "cost": "INT64",
            "role": "STRING",
            "shop_unit": "BOOL",
            "stats": "JSON",
        },
        _units,
    ),
    "unit_innate_traits": ReferenceTable(
        {
            "name": "STRING",
            "api_name": "STRING",
            "trait_name": "STRING",
            "trait_api_name": "STRING",
        },
        _unit_innate_traits,
    ),
}
